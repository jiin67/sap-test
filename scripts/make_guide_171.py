wb = Workbook()


def sheet(name, widths, first=False):
    ws = wb.active if first else wb.create_sheet()
    ws.title = name
    for i, w in enumerate(widths):
        ws.column_dimensions[chr(65 + i)].width = w
    ws.sheet_view.showGridLines = False
    return ws


def title(ws, r, text, sub=None):
    ws.cell(r, 1, text).font = Font(size=16, bold=True, color=NAVY)
    if sub:
        ws.cell(r + 1, 1, sub).font = Font(italic=True, color="595959")
        return r + 3
    return r + 2


def section(ws, r, text, ncol):
    for c in range(1, ncol + 1):
        ws.cell(r, c).fill = F_SEC
    ws.cell(r, 1, text).font = Font(size=12, bold=True, color=NAVY)
    return r + 1


def head(ws, r, cells):
    for i, v in enumerate(cells, 1):
        c = ws.cell(r, i, v)
        c.fill, c.font, c.alignment, c.border = F_HEAD, Font(bold=True, color=WHITE), CENTER, BOX
    return r + 1


def row(ws, r, cells, fill=None, center_cols=()):
    for i, v in enumerate(cells, 1):
        c = ws.cell(r, i, v)
        c.alignment = CENTER if i in center_cols else WRAP
        c.border = BOX
        if fill:
            c.fill = fill
    return r + 1


def para(ws, r, text, ncol, fill=None, bold=False):
    ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=ncol)
    c = ws.cell(r, 1, text)
    c.alignment = WRAP
    c.font = Font(bold=bold)
    if fill:
        c.fill = fill
    lines = sum(max(1, len(x) // 95 + 1) for x in text.split("\n"))
    ws.row_dimensions[r].height = 16 * lines + 4
    return r + 1


