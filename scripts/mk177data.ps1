            (M '2026091990006' 'INDATE=2026.09.19;ISFREE=Y;TEXTINFO=ZTEST_20260919 F-no-wrtdate'),
            (M '2026091990007' 'INDATE=2026.09.19;ISFREE=Y;TEXTINFO=ZTEST_20260919 G-mixed-items'),
